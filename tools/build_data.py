"""Step 2: combine base.json (CEFR list + WordNet) with hand-written Turkish
meanings/examples in tools/authored/*.txt and phrasal verbs in
tools/phrasal.txt, then emit data/words.js and data/phrasal.js.

authored line:  word|pos|turkish|example with {target form}   (example optional)
phrasal line:   phrasal verb|level|turkish|english definition|example with {form}
"""
import glob, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
AB = {'n': 'noun', 'v': 'verb', 'adj': 'adjective', 'adv': 'adverb', 'prep': 'preposition', 'conj': 'conjunction',
      'pron': 'pronoun', 'det': 'determiner', 'num': 'number', 'int': 'interjection', 'modal': 'modal auxiliary',
      'be': 'be-verb', 'do': 'do-verb', 'have': 'have-verb', 'inf': 'infinitive-to'}

def forms_rx(w):
    b = re.escape(w)
    stem = re.escape(w[:-1])
    return re.compile(r'\b(' + b + r'(?:s|es|ed|d|ing|er|est)?|' + stem + r'(?:ied|ies|ing|ed|ier|iest)|' + b + r'[a-z](?:ed|ing|er|est))\b', re.I)

base = json.load(open(os.path.join(HERE, 'base.json'), encoding='utf-8'))
idx = {(e['w'].lower(), e['pos']): e for e in base}
missing, problems = [], []
for f in sorted(glob.glob(os.path.join(HERE, 'authored', '*.txt'))):
    for n, line in enumerate(open(f, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('#'):
            continue
        parts = line.split('|')
        if len(parts) < 3:
            problems.append(f'{os.path.basename(f)}:{n} bad line'); continue
        w, pos, tr = parts[0].strip(), parts[1].strip(), parts[2].strip()
        ex = '|'.join(parts[3:]).strip()
        pos = AB.get(pos, pos)
        e = idx.get((w.lower(), pos))
        if not e:
            problems.append(f'{os.path.basename(f)}:{n} unknown {w}|{pos}'); continue
        e['tr'] = tr
        if ex:
            if '{' not in ex:
                problems.append(f'{os.path.basename(f)}:{n} no marker'); continue
            e['ex'] = ex
            e['ex_src'] = 'authored'

words = []
for e in base:
    if e.get('tr') == '-':  # offensive / unsuitable entry, excluded on purpose
        continue
    if e['level'] == 'A1' or not e.get('tr'):
        if e['level'] != 'A1': missing.append(e['w'] + '|' + e['pos'])
        continue
    ex = e.get('ex', '')
    if ex and '{' not in ex:
        m = forms_rx(e['w']).search(ex)
        ex = ex[:m.start()] + '{' + m.group(0) + '}' + ex[m.end():] if m else ''
    if ex:
        ex = ex[0].upper() + ex[1:]
        if ex[-1] not in '.!?"': ex += '.'
    words.append([e['w'], e['pos'], e['level'], e['tr'], e.get('def', ''), ex])

LV = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2']
words.sort(key=lambda r: (LV.index(r[2]), r[0].lower()))
os.makedirs(os.path.join(ROOT, 'data'), exist_ok=True)
with open(os.path.join(ROOT, 'data', 'words.js'), 'w', encoding='utf-8') as out:
    out.write('// Generated by tools/build_data.py — [word, pos, CEFR, Turkish, WordNet definition, example]\n')
    out.write('window.WORDS=' + json.dumps(words, ensure_ascii=False, separators=(',', ':')) + ';\n')

pv = []
pf = os.path.join(HERE, 'phrasal.txt')
if os.path.exists(pf):
    for n, line in enumerate(open(pf, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('#'): continue
        p = [x.strip() for x in line.split('|')]
        if len(p) != 5 or p[1] not in LV or '{' not in p[4]:
            problems.append(f'phrasal.txt:{n} bad line'); continue
        pv.append(p)
seen = set(); pv = [p for p in pv if not (p[0] in seen or seen.add(p[0]))]
with open(os.path.join(ROOT, 'data', 'phrasal.js'), 'w', encoding='utf-8') as out:
    out.write('// Generated by tools/build_data.py — [phrasal verb, CEFR, Turkish, definition, example]\n')
    out.write('window.PHRASAL=' + json.dumps(pv, ensure_ascii=False, separators=(',', ':')) + ';\n')

from collections import Counter
print('words', len(words), Counter(r[2] for r in words), 'phrasal', len(pv))
print('with example', sum(1 for r in words if r[5]), 'missing tr', len(missing))
for p in problems[:50]: print('!!', p)
if '-v' in sys.argv: print('\n'.join(missing[:100]))
