"""Map vocabulary items to Microsoft Fluent Emoji illustrations (MIT license).

A word gets an illustration when it appears in an emoji's CLDR name, or when it
is one of that emoji's keywords and the keyword is specific (used by <= 3
emojis). Copies the matched Color SVGs to images/emoji/ and writes
data/illustrations.js (window.ILLUS = {"word|pos": "file.svg"}).

usage: python3 tools/map_illustrations.py PATH_TO/fluentui-emoji
"""
import json, os, re, shutil, sys
from collections import defaultdict
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
SRC = os.path.join(sys.argv[1], 'assets')
OUT = os.path.join(ROOT, 'images', 'emoji')
# generic or misleading keywords never used for matching
STOP = set('face person man woman people hand human body sign symbol mark object other thing time day '
           'good bad up down on off out in go play small big great old new top cool fine free light'.split())

# hand-checked corrections: words whose automatic match shows a different meaning
REJECT = set('ball bar board box dish head leg machine nose note office stone way green lamp lip root sake speaker suit '
             'chain engine horn pole pot pick score mate tray index disc pistol wedge dizzy'.split())
FORCE = {'car': 'automobile', 'football': 'soccer ball', 'tree': 'deciduous tree', 'tea': 'teacup without handle'}
emojis = []
for d in sorted(os.listdir(SRC)):
    meta = os.path.join(SRC, d, 'metadata.json')
    color = os.path.join(SRC, d, 'Color')
    if not os.path.exists(meta) or not os.path.isdir(color):
        continue
    svgs = [f for f in os.listdir(color) if f.endswith('.svg')]
    if not svgs:
        continue
    m = json.load(open(meta, encoding='utf-8'))
    if m.get('group') in ('Flags', 'Symbols') or 'skin tone' in m.get('cldr', ''):
        continue
    emojis.append((m['cldr'].lower(), [k.lower() for k in m.get('keywords', [])], os.path.join(color, svgs[0])))

by_name, by_kw = defaultdict(list), defaultdict(list)
for i, (cldr, kws, _) in enumerate(emojis):
    by_name[cldr].append(i)
    for tok in set(re.findall(r'[a-z]+', cldr)):
        by_name[tok].append(i)
    for k in kws:
        by_kw[k].append(i)

words = json.loads(open(os.path.join(ROOT, 'data', 'words.js'), encoding='utf-8').read().split('=', 1)[1].rstrip(';\n'))
os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    os.remove(os.path.join(OUT, f))
mapping, used = {}, {}
for w, pos, lvl, *_ in words:
    if pos not in ('noun', 'verb', 'adjective') or len(w) < 3:
        continue
    lw = w.lower()
    if lw in STOP:
        continue
    # strict rules: exact CLDR name; noun = head noun of the name ("pickup truck");
    # adjective = emotion face ("worried face"). No keyword guessing.
    if lw in REJECT:
        continue
    names = [i for i, e in enumerate(emojis) if e[0] == FORCE.get(lw, lw)]
    if not names and pos == 'noun':
        names = sorted((i for i in by_name.get(lw, []) if emojis[i][0].split()[-1] == lw and len(emojis[i][0].split()) <= 2),
                       key=lambda i: len(emojis[i][0]))
    if not names and pos == 'adjective':
        names = [i for i in by_name.get(lw, []) if emojis[i][0] == lw + ' face']
    if not names or pos == 'verb' and emojis[names[0]][0] != lw:
        continue
    if pos == 'verb':
        continue
    pick = names[0]
    src = emojis[pick][2]
    name = os.path.basename(src)
    if name not in used:
        shutil.copy(src, os.path.join(OUT, name))
        used[name] = 1
    mapping[f'{w}|{pos}'] = name
with open(os.path.join(ROOT, 'data', 'illustrations.js'), 'w', encoding='utf-8') as out:
    out.write('// Generated by tools/map_illustrations.py — Microsoft Fluent Emoji (MIT)\n')
    out.write('window.ILLUS=' + json.dumps(mapping, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(mapping), 'words ->', len(used), 'illustrations')
